    private fun p(regex: String, render: (List<String>) -> String): Pair<Regex, (List<String>) -> String> = Regex(regex) to render

    /** NotFoundException 의 대상. "반(이름)" 처럼 이름이 붙은 것도 처리 */
    private fun noun(ko: String): String {
        val named = Regex("(.+?)\\((.+)\\)").matchEntire(ko.trim())
        return if (named != null) "${term(named.groupValues[1])} (${named.groupValues[2]})" else term(ko)
    }

    private fun plural(count: String, one: String, many: String) = if (count == "1") one else many

