 * 서버 코드는 한국어 메시지를 그대로 던지고, 응답 직전에 요청 언어가 영어면 여기서 바꾼다.
 * 찾는 순서: ① 한국어 문장 그대로 → ② 숫자·이름이 끼어 있는 문장(정규식) → ③ 오류 코드별 일반 문장 → ④ 상태별 일반 문장.
 * 새 오류를 추가할 때 이 사전에 없으면 ③·④ 로 떨어지므로 영어 화면에도 뜻은 전달된다(대신 덜 구체적).
 * 문장 안의 사용자 데이터(반 이름·질문 등)는 번역하지 않는다.
 */
object ErrorMessagesEn {

    fun translate(code: String, message: String, status: Int): String {
        val m = message.trim()
        EXACT[m]?.let { return it }
        for ((regex, render) in PATTERNS) {
            val match = regex.matchEntire(m) ?: continue
            return render(match.groupValues.drop(1))
        }
        BY_CODE[code]?.let { return it }
        return when (status) {
            400 -> "Please check your input."
            401 -> "Authentication failed."
            403 -> "You don't have permission to do this."
            404 -> "Not found."
            409 -> "This request conflicts with the current state."
            422 -> "The request could not be processed."
            429 -> "Too many requests. Please try again shortly."
            else -> "The request could not be processed."
        }
    }

